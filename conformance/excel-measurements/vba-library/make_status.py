"""Writes STATUS.md (per-function conformance against Excel VBA) and differences.tsv (every
differing line with its class) from the vba_library_excel.rs reports.

  VBA_LIBRARY_REPORT=<base> cargo test -p calcvba-differential --test vba_library_excel
  python -I make_status.py <base>.vm3.tsv <base>.jit.tsv

Classes, most serious first:
  missing  - the module or case does not bind or run in CalcVBA (unresolved name, unsupported
             construct, panic)
  error    - Excel raises an error and CalcVBA does not, or the reverse, or another error number
  type     - both give a value, of different types
  value    - same type, different value (Double/Single more than 4 ulps apart, or any other type)
  lastbit  - same type, Double/Single within 4 ulps
Cases marked "' locale" in the probe source are counted separately: their answers depend on the
regional settings of the machine Excel ran on.
"""

import csv
import glob
import os
import re
import struct
import sys
from collections import Counter, defaultdict

HERE = os.path.dirname(os.path.abspath(__file__))
PROBES = os.path.join(HERE, "probes")
ORDER = ["missing", "error", "type", "value", "lastbit"]


def ulps(a, b, single):
    if single:
        ia, ib = (struct.unpack("<i", struct.pack("<I", int(x, 16)))[0] for x in (a, b))
    else:
        ia, ib = (struct.unpack("<q", struct.pack("<Q", int(x, 16)))[0] for x in (a, b))
    fix = lambda i: i if i >= 0 else -(i & (0x7FFFFFFF if single else 0x7FFFFFFFFFFFFFFF))
    return abs(fix(ia) - fix(ib))


def classify(want, have):
    w = want.split("=", 1)[1] if "=" in want else want
    h = have.split("=", 1)[1] if "=" in have else have
    if have.startswith("<") or have in ("run fails", "<missing>"):
        return "missing"
    if w.startswith("ERR") or h.startswith("ERR"):
        return "error"
    wt, ht = w.split(":", 1)[0], h.split(":", 1)[0]
    if wt != ht:
        return "type"
    if wt in ("Double", "Single", "Date"):
        mw, mh = re.match(r"\w+:([0-9A-F]+)", w), re.match(r"\w+:([0-9A-F]+)", h)
        if mw and mh and ulps(mw.group(1), mh.group(1), wt == "Single") <= 4:
            return "lastbit"
    return "value"


def locale_cases():
    out = defaultdict(set)
    for path in glob.glob(os.path.join(PROBES, "P_*.bas")):
        module = os.path.splitext(os.path.basename(path))[0]
        for line in open(path, encoding="utf-8", errors="replace"):
            m = re.match(r"\s*Case\s+(\d+)\b.*'.*\blocale\b", line, re.I)
            if m:
                out[module].add(int(m.group(1)))
    return out


def load(path):
    diffs = {}
    for row in open(path, encoding="utf-8"):
        row = row.rstrip("\n")
        if not row:
            continue
        parts = row.split("\t")
        if len(parts) < 3:
            continue
        diffs[(parts[0], parts[1])] = parts[2]
    return diffs


def main():
    vm3, jit = load(sys.argv[1]), load(sys.argv[2])
    loc = locale_cases()
    functions = {r["name"]: r for r in csv.DictReader(open(os.path.join(HERE, "functions.tsv"), encoding="utf-8"), delimiter="\t")}
    rows, all_diffs = [], []
    totals = Counter()
    for path in sorted(glob.glob(os.path.join(PROBES, "P_*.excel.txt"))):
        module = os.path.basename(path)[: -len(".excel.txt")]
        lines = [l for l in open(path, encoding="utf-8").read().splitlines() if l]
        stats = Counter()
        for want in lines:
            key = want.split("=", 1)[0]
            k = int(key.rsplit(".", 1)[1]) if key.rsplit(".", 1)[-1].isdigit() else 0
            is_loc = k in loc.get(module, set())
            classes = {}
            for name, d in (("vm3", vm3), ("jit", jit)):
                have = d.get((module, want))
                if have is not None:
                    classes[name] = classify(want, have)
                    all_diffs.append((module, name, classes[name], "locale" if is_loc else "", want, have))
            stats["cases"] += 1
            stats["locale"] += is_loc
            stats["vm3_ok"] += "vm3" not in classes
            stats["jit_ok"] += "jit" not in classes
            worst = min((ORDER.index(c) for c in classes.values()), default=None)
            if worst is not None:
                stats[ORDER[worst]] += 1
        totals.update(stats)
        rows.append((module, stats))
    with open(os.path.join(HERE, "differences.tsv"), "w", encoding="utf-8", newline="\n") as f:
        f.write("module\texecutor\tclass\tlocale\texcel\tcalcvba\n")
        for d in all_diffs:
            f.write("\t".join(d) + "\n")
    with open(os.path.join(HERE, "STATUS.md"), "w", encoding="utf-8", newline="\n") as f:
        f.write("# VBA library against Excel VBA: status\n\n")
        f.write("Generated by make_status.py from the vba_library_excel.rs reports. One probe module per "
                "library function (functions.tsv: VBE7.DLL's type library plus MS-VBAL section 6); every "
                "line is a case. Bit-exact is the only passing state.\n\n")
        f.write(f"**{totals['cases']} cases in {len(rows)} modules.** Matching Excel exactly: VM3 "
                f"{totals['vm3_ok']} ({100 * totals['vm3_ok'] // max(1, totals['cases'])}%), JIT "
                f"{totals['jit_ok']} ({100 * totals['jit_ok'] // max(1, totals['cases'])}%). Worst class per "
                f"differing case: missing {totals['missing']}, error {totals['error']}, type {totals['type']}, "
                f"value {totals['value']}, last bit {totals['lastbit']}. Cases marked locale: "
                f"{totals['locale']}.\n\n")
        f.write("Classes, most serious first: **missing** (does not bind or run), **error** (error behaviour "
                "differs), **type**, **value**, **lastbit** (Double/Single within 4 ulps). The full list is "
                "differences.tsv; Excel refusals CalcVBA accepts are in known-differences.txt as "
                "`refusal:` lines.\n\n")
        f.write("| Module | Cases | VM3 exact | JIT exact | missing | error | type | value | last bit | locale cases |\n")
        f.write("|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|\n")
        for module, s in rows:
            f.write(f"| {module[2:]} | {s['cases']} | {s['vm3_ok']} | {s['jit_ok']} | {s['missing'] or ''} | "
                    f"{s['error'] or ''} | {s['type'] or ''} | {s['value'] or ''} | {s['lastbit'] or ''} | "
                    f"{s['locale'] or ''} |\n")
    print(totals)


if __name__ == "__main__":
    main()
